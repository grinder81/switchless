/** Generate docs/action-catalog.md from src/catalog. Re-run after any catalog change. */
import { writeFileSync } from "node:fs";
import { ACTIONS } from "../src/catalog/actions.js";
import { SERVICES, type ServiceId } from "../src/catalog/services.js";
import { loadSplit } from "../src/data/banking77.js";

const train = loadSplit("train");
const countByIntent = new Map<string, number>();
const exampleByIntent = new Map<string, string>();
for (const ex of train) {
  countByIntent.set(ex.intent, (countByIntent.get(ex.intent) ?? 0) + 1);
  if (!exampleByIntent.has(ex.intent)) exampleByIntent.set(ex.intent, ex.text);
}

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const lines: string[] = [
  "# Action catalogue",
  "",
  "<!-- Generated by `pnpm docs:catalog` from src/catalog. Do not edit by hand. -->",
  "",
  `Kestrel Bank exposes **${ACTIONS.length} actions** across **${Object.keys(SERVICES).length} services**.`,
  "Each action answers exactly one Banking77 intent. Example messages and counts come from the train split.",
  "",
  "| Service | Actions | Train messages |",
  "|---|---:|---:|",
];
for (const [id, s] of Object.entries(SERVICES)) {
  const acts = ACTIONS.filter((a) => a.service === id);
  const n = acts.reduce((sum, a) => sum + (countByIntent.get(a.intent) ?? 0), 0);
  lines.push(`| ${s.title} | ${acts.length} | ${n} |`);
}
for (const [id, s] of Object.entries(SERVICES) as [ServiceId, (typeof SERVICES)[ServiceId]][]) {
  lines.push("", `## ${s.title} (\`${id}\`)`, "", s.description, "");
  lines.push("| Action | Banking77 intent | What the customer wants | Handler | Example message |");
  lines.push("|---|---|---|---|---|");
  for (const a of ACTIONS.filter((x) => x.service === id)) {
    lines.push(
      `| \`${a.id}\` | \`${a.intent}\` | ${cell(a.description)} | ${cell(a.handler)} | "${cell(exampleByIntent.get(a.intent) ?? "")}" |`,
    );
  }
}
writeFileSync(new URL("../docs/action-catalog.md", import.meta.url), `${lines.join("\n")}\n`);
console.log("wrote docs/action-catalog.md");
