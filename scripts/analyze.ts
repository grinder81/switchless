/**
 * Recompute the reported statistics from the preserved raw runs. No network, no API calls.
 *
 *   pnpm analyze        # verifies results/raw/SHA256SUMS, writes results/analysis.md
 */
import { writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import {
  type Interval,
  isCorrect,
  jaccard,
  pairedComparison,
  referLeastConfident,
  selectionBreakdown,
  verifyManifest,
  wilson,
} from "../src/bench/analysis.js";
import { serviceAccuracy } from "../src/bench/metrics.js";
import { readRun } from "../src/bench/runner.js";
import { STATE_CHANGING } from "../src/catalog/effects.js";
import { countLoc } from "./count-loc.js";

const { values } = parseArgs({
  options: {
    dir: { type: "string", default: "results/raw" },
    out: { type: "string", default: "results/analysis.md" },
  },
});
const DIR = values.dir;

const manifest = verifyManifest(DIR);
const run = (name: string) => readRun(`${DIR}/${name}.jsonl`);
const ROUTERS = ["rules", "jev", "llm", "hybrid"] as const;
const LABEL: Record<string, string> = {
  rules: "Rules",
  jev: "JEV",
  llm: "LLM (gpt-6-luna)",
  hybrid: "Hybrid",
};
const SPLITS = [
  ["test_3080", "Test split (3,080 messages)"],
  ["train_1000", "Held-out train sample (1,000 messages)"],
] as const;

const pct = (x: number, d = 1) => `${(100 * x).toFixed(d)}%`;
const ci = (i: Interval) => `${pct(i.estimate)} (${pct(i.lo)}–${pct(i.hi)})`;
const pts = (x: number) => `${x >= 0 ? "+" : "−"}${Math.abs(100 * x).toFixed(2)}`;

const out: string[] = [
  "# Analysis of the preserved raw runs",
  "",
  "Generated by `pnpm analyze` from `results/raw/` (no API calls). Do not edit by hand.",
  "",
  `Manifest: all ${manifest.length} files in \`${DIR}/\` match their full SHA-256 hashes in \`SHA256SUMS\`.`,
  "",
  "Intervals are 95%. They describe sampling uncertainty over these messages only: they do **not**",
  "capture model drift (the LLM has no pinned version), variation between repeated API runs (see the",
  "consistency check in `docs/final-results.md`), or other datasets and domains.",
  "",
];

// 1. Accuracy with intervals
out.push("## 1. Accuracy with 95% intervals", "");
out.push(
  "Exact action accuracy over all messages (a referral to a person counts as not correct), with a",
  "Wilson score interval. Service accuracy is shown without an interval for reference.",
  "",
);
for (const [split, title] of SPLITS) {
  out.push(
    `### ${title}`,
    "",
    "| Router | Exact action (95% CI) | Right service | Lines of code |",
    "|---|---|---:|---:|",
  );
  for (const r of ROUTERS) {
    const rs = run(`${r}_${split}`);
    const correct = rs.filter(isCorrect).length;
    out.push(
      `| ${LABEL[r]} | ${ci(wilson(correct, rs.length))} | ${pct(serviceAccuracy(rs))} | ${countLoc(r)} |`,
    );
  }
  out.push("");
}
out.push(
  "Lines of code: a router's own files plus the routers it is built from (`scripts/count-loc.ts`); the",
  "hybrid's 888 = 56 own + 772 rules + 60 JEV. This is this implementation's integration code, not a",
  "measure of model complexity or total operating burden.",
  "",
);

// 2. Paired comparison
out.push("## 2. LLM vs JEV, paired by message", "");
for (const [split, title] of SPLITS) {
  const p = pairedComparison(run(`jev_${split}`), run(`llm_${split}`));
  out.push(
    `### ${title}`,
    "",
    "| | |",
    "|---|---|",
    `| Messages only JEV got right / only the LLM got right | ${p.onlyA} / ${p.onlyB} |`,
    `| Observed LLM − JEV difference | ${pts(p.diff.estimate)} points |`,
    `| Paired 95% CI (Wald) | ${pts(p.diff.lo)} to ${pts(p.diff.hi)} points |`,
    `| Paired 95% CI (bootstrap, 10,000 resamples, seed 1) | ${pts(p.bootstrap.lo)} to ${pts(p.bootstrap.hi)} points |`,
    `| McNemar (continuity-corrected) | χ² = ${p.mcnemarChi2.toFixed(2)}, p = ${p.mcnemarP.toFixed(2)} |`,
    "",
  );
}
{
  const p = pairedComparison(run("jev_test_3080"), run("llm_test_3080"));
  out.push(
    `On the test split, the observed LLM advantage was ${Math.abs(100 * p.diff.estimate).toFixed(2)} percentage points; the paired`,
    `95% confidence interval ranged from ${pts(p.diff.lo)} to ${pts(p.diff.hi)} points. No difference was detected; this is not`,
    "evidence that the two are equivalent.",
    "",
  );
}

// 3. Matched referral volume
const hybridTest = run("hybrid_test_3080");
const budget = hybridTest.filter((r) => r.action === null).length;
const hybridReferred = new Set(hybridTest.filter((r) => r.action === null).map((r) => r.index));
out.push(
  "## 3. Same number of referrals (exploratory)",
  "",
  `The hybrid referred ${budget} of ${hybridTest.length} test messages (${pct(budget / hybridTest.length)}) to a person. Here JEV and the`,
  `LLM each refer the same **number** of messages: their ${budget} least confident, ties broken by referring the`,
  "lower dataset index first. This equalises referral volume, not which messages are referred or how much",
  "human effort they need: the overlap column shows how different the referred sets are.",
  "",
  "This is exploratory. The JEV and LLM cut-offs were chosen on the test split to match a count, not",
  "fixed in advance; the hybrid's design and threshold were frozen on separate tuning data (D12). The",
  "rules router is shown at its own referral rate, which is close but not matched.",
  "",
  "| Router | Referred | Right on answered (95% CI) | Incorrect automatic selections | Referred set overlap with hybrid's | Tied at cut (referred) | Range if ties reordered |",
  "|---|---:|---|---:|---:|---|---|",
);
const rows: [string, ReturnType<typeof referLeastConfident>][] = [];
for (const r of ["jev", "llm"] as const) {
  const rs = run(`${r}_test_3080`);
  const ref = referLeastConfident(rs, budget);
  out.push(
    `| ${LABEL[r]}, confidence-gated | ${ref.referred} | ${ci(ref.accuracy)} | ${ref.answered - ref.correct} | ${pct(jaccard(ref.referredIndices, hybridReferred))} | ${ref.tiedAtCut} at ${ref.cutConfidence.toFixed(4)} (${ref.tiedReferred}) | ${pct(ref.tieWorst)}–${pct(ref.tieBest)} |`,
  );
  rows.push([r, ref]);
}
for (const r of ["hybrid", "rules"] as const) {
  const rs = run(`${r}_test_3080`);
  const answered = rs.filter((x) => x.action !== null);
  const s = selectionBreakdown(rs);
  const ov =
    r === "hybrid"
      ? "–"
      : pct(jaccard(new Set(rs.filter((x) => x.action === null).map((x) => x.index)), hybridReferred));
  out.push(
    `| ${LABEL[r]} | ${rs.length - answered.length} | ${ci(wilson(answered.length - s.incorrect, answered.length))} | ${s.incorrect} | ${ov} | – | – |`,
  );
}
out.push(
  "",
  "_Tied at cut_: messages whose confidence equals the lowest answered confidence, and how many of them",
  "were referred. _Range if ties reordered_: accuracy on answered if those tied messages were referred",
  "in the least / most favourable order. JEV's confidences are nearly continuous; the LLM self-reports",
  "rounded values (for example 0.99), so its cut can fall inside a large tie.",
  "",
);

// 4. Selections and handlers
const stateList = [...STATE_CHANGING.keys()].map((id) => `\`${id}\``).join(", ");
out.push(
  "## 4. Incorrect selections and state-changing handlers",
  "",
  `${STATE_CHANGING.size} of the 77 handlers can change bank state (\`src/catalog/effects.ts\`, checked by`,
  "`tests/effects.test.ts`, which runs every handler for every seed customer); the rest only return",
  "information. The counts below are **selections** read from prediction logs: the router chose a",
  "handler that *can* change state. Whether a selection would actually change anything depends on the",
  "customer's accounts, and no selection here was executed against real customer state, so these are",
  "not counts of observed harmful actions.",
  "",
  "Test split, each router as run (the gated JEV and LLM rows of section 3 are not repeated here).",
  "",
  "| Router | Selections | Incorrect selections | …of a state-changing handler | …of which the right action was information-only | Safety-critical exact-intent recall (95% CI) |",
  "|---|---:|---:|---:|---:|---|",
);
for (const r of ROUTERS) {
  const s = selectionBreakdown(run(`${r}_test_3080`));
  out.push(
    `| ${LABEL[r]} | ${s.selected} | ${s.incorrect} | ${s.incorrectStateChangingHandler} | ${s.incorrectStateChangingWhenGoldReadOnly} | ${ci(wilson(s.safetyExact, s.safetyGold))} |`,
  );
}
out.push("");
for (const [r, ref] of rows) {
  const rs = run(`${r}_test_3080`).filter((x) => !ref.referredIndices.has(x.index));
  const s = selectionBreakdown(rs);
  out.push(
    `At the matched referral volume, ${LABEL[r]} made ${s.incorrect} incorrect selections, ${s.incorrectStateChangingHandler} of them of a state-changing handler.`,
  );
}
out.push(
  "",
  "_Safety-critical exact-intent recall_: of messages labelled with one of the five safety-critical",
  "intents, the share where the router chose exactly that intent's action. It does not measure whether",
  "an appropriate protective action happened (a different protective action, or a person, may also have",
  "protected the customer).",
  "",
  `State-changing handlers: ${stateList}.`,
  "",
);

writeFileSync(values.out, `${out.join("\n")}\n`);
console.log(`verified ${manifest.length} raw files; wrote ${values.out}`);
